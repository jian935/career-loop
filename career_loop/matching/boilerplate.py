# -*- coding: utf-8 -*-
"""JD 样板文字清除：把招聘平台自带的无信息量文字剥掉，再进匹配引擎。

## 为什么需要（v0.8.14，公开中文 JD 数据集实测发现）
公开中文 JD 集（HuggingFace ngtranai09/china_job，8,674 条真实 JD）里，
每条 JD 都带采集来源声明，多数还带平台反诈免责声明：

  3,563 条含「职位来源于智联招聘」/「该职位来源于猎聘」/「职位来源于实习僧」
  2,101 条含「以担保或任何理由索要财物，扣押证照，均涉嫌违法。」

（判定方法：全数据集按句号切句，出现 ≥150 次的句子即样板，只有这两条过线。）

这两句对判断岗位族**毫无信息量**，却让词表里的「招聘」（hr 族）和「证照」
（admin 族）在 75% / 41% 的 JD 上误命中——实测 hr 词表在中文集上的族精确率
仅 2.5%、admin 仅 10.6%，主因就是它们。用户从这些网站复制 JD 粘贴进来时
会原样带入，所以这不是"评测集特有的脏数据"，是产品就要处理的真实输入。

## 边界（刻意收窄）
- 只剥平台固有样板，不碰任何岗位内容——模式都要求出现平台特有措辞；
- 剥晚了不如剥早：在 detect_domains / extract_by_rules 入口剥，
  用户看到的 quote 也不再带免责声明；
- 网页 JS 引擎用同一份模式（sync_web_vocab.py 自动生成），两端一致。
"""

from __future__ import annotations

import re

#: 平台样板模式。刻意保守：每条都要求出现平台特有措辞，
#: 宁可漏剥，不能误剥岗位内容。
BOILERPLATE_PATTERNS: tuple[re.Pattern[str], ...] = (
    # 采集来源声明：「职位来源于智联招聘」「该职位来源于猎聘」「职位来源于：实习僧」
    re.compile(r"(?:该|此)?职位来源于[：:]?[^\s。，,；;！!？?]{2,16}"),
    # 平台反诈免责声明：「以担保或任何理由索要财物，扣押证照，均涉嫌违法。」
    # 放宽到「以…理由索要财物…涉嫌违法」，同句内两个锚点都在才算。
    re.compile(r"以[^。；;\n]{0,15}理由索要财物[，,]?[^。；;\n]{0,25}涉嫌违法"),
)


def strip_boilerplate(text: str) -> str:
    """剥掉 JD 里的平台样板文字。没有样板时原样返回（同一对象）。"""
    if not text:
        return text
    out = text
    for pat in BOILERPLATE_PATTERNS:
        out = pat.sub("", out)
    return out
