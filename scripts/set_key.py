# -*- coding: utf-8 -*-
"""Write .env from a key file without printing the key.

Usage:
    python scripts/set_key.py --file E:\\Agent\\.deepseek_key [--delete]

The key file can contain just the key on the first line, or `sk-...`.
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV = ROOT / ".env"


def mask(key: str) -> str:
    if len(key) <= 8:
        return "*" * len(key)
    return key[:3] + "*" * (len(key) - 7) + key[-4:]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--file", default=r"E:\Agent\.deepseek_key",
                    help="文本文件，第一行是 sk-... 开头的 key")
    ap.add_argument("--base", default="https://api.deepseek.com")
    ap.add_argument("--model", default="deepseek-flash")
    ap.add_argument("--delete", action="store_true", help="写入后删除 key 文件")
    args = ap.parse_args()

    path = Path(args.file)
    if not path.exists():
        print(f"找不到 key 文件：{path}")
        print("请新建一个文本文件，第一行粘贴 sk- 开头的 key。")
        return 1

    first = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            first = line.strip()
            break
    if not first.startswith("sk-") or "PASTE" in first.upper():
        print("还没填 Key：请把 sk-PASTE-HERE 替换成你的真实 Key 再保存。")
        return 1

    ENV.write_text(
        "\n".join([
            "# generated by scripts/set_key.py",
            f"OPENAI_API_KEY={first}",
            f"OPENAI_BASE_URL={args.base}",
            f"OPENAI_MODEL={args.model}",
        ]) + "\n",
        encoding="utf-8",
    )
    print(f"已写入 {ENV}")
    print(f"  key   {mask(first)}")
    print(f"  base  {args.base}")
    print(f"  model {args.model}")

    if args.delete:
        path.unlink(missing_ok=True)
        print(f"已删除 key 文件：{path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
